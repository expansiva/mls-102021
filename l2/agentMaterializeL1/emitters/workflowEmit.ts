// The mechanical files of the workflow service of a module (materializadorL1.md §11): the Task adapter every
// process function calls, and the module tick that runs the scheduled processes. The functions themselves are
// written by the model from the l4 prose (steps/workflows45).

import type { M12FileInfo } from '/_102021_/l2/agentMaterializeL1/helpers/m12Names.js';

const PLATFORM_CONTRACTS = '/_102034_/l1/server/layer_2_controllers/contracts.js';

/** The Task adapter of a module: the one place that will call collab-messages. */
export function taskOccurrenceFile(project: number, moduleName: string): M12FileInfo {
  return { project, level: 1, folder: `${moduleName}/layer_1_external/adapters/workflow`, shortName: 'taskOccurrence', extension: '.ts' };
}

/** The module tick, next to the module's composition root (the persistence folder the runtime already loads). */
export function moduleTickFile(project: number, moduleName: string): M12FileInfo {
  return { project, level: 1, folder: `${moduleName}/layer_1_external/adapters/persistence`, shortName: 'moduleTick', extension: '.ts' };
}

export function workflowFile(project: number, moduleName: string, processId: string): M12FileInfo {
  return { project, level: 1, folder: `${moduleName}/layer_2_application/workflows`, shortName: processId, extension: '.ts' };
}

export function moduleSpecifier(info: M12FileInfo): string {
  return `/_${info.project}_/l${info.level}/${info.folder}/${info.shortName}.js`;
}

/**
 * The Task of an occurrence of a module process. The business record stays in the module table; the Task keeps the
 * reference `{ project, module, entity, recordId, processId, workflowVersion }` and the progress `{ step, actorNow,
 * history }`. The collab-messages contract for it does not exist yet (TaskData has no field for the reference nor
 * the progress: todo/collabMessages/tasks/backlog/fromHow_task_da_ocorrencia_de_modulo.md). Until it does, this
 * adapter keeps the progress in the process memory and logs TASK_ADAPTER_PENDING on every write, so the workflow
 * service runs, is tested, and nobody mistakes it for the real Task.
 */
export function taskOccurrenceSource(project: number, moduleName: string): string {
  const info = taskOccurrenceFile(project, moduleName);
  return [
    `/// <mls fileReference="_${project}_/l1/${info.folder}/${info.shortName}.ts" enhancement="_blank"/>`,
    `import type { RequestContext } from '${PLATFORM_CONTRACTS}';`,
    '',
    '// Generated by agentMaterializeL1 (materializadorL1.md §11). Not a Task yet: see the note on taskOccurrence.',
    '',
    'export interface OccurrenceRef {',
    '  project: number;',
    '  module: string;',
    '  entity: string;',
    '  recordId: string;',
    '  processId: string;',
    '  workflowVersion: string;',
    '}',
    '',
    'export interface OccurrenceStep {',
    '  step: string;',
    '  actor: string;',
    '  at: string;',
    '}',
    '',
    'export interface TaskOccurrence {',
    '  ref: OccurrenceRef;',
    '  /** The step the occurrence is in and who acts now. */',
    '  step: string;',
    '  actorNow: string;',
    '  history: OccurrenceStep[];',
    '  /** The key of the submission that opened it (`ctx.requestMeta.requestId`): the same key opens nothing twice. */',
    '  openedBy: string;',
    '}',
    '',
    'export interface TaskOccurrencePort {',
    '  /** Opens the occurrence of a record; a key already used returns the occurrence it opened. */',
    '  open(ctx: RequestContext, ref: OccurrenceRef, step: string, actorNow: string, key: string): Promise<TaskOccurrence>;',
    '  /** The occurrence of a record of a process, or null when none was opened. */',
    '  find(ctx: RequestContext, ref: Omit<OccurrenceRef, \'workflowVersion\'>): Promise<TaskOccurrence | null>;',
    '  /** Moves the occurrence to a step, with who acts now; the step is appended to its history. */',
    '  advance(ctx: RequestContext, ref: Omit<OccurrenceRef, \'workflowVersion\'>, step: string, actorNow: string): Promise<TaskOccurrence>;',
    '}',
    '',
    'const byRecord = new Map<string, TaskOccurrence>();',
    'const byKey = new Map<string, string>();',
    '',
    'function recordKey(ref: Omit<OccurrenceRef, \'workflowVersion\'>): string {',
    '  return `${ref.project}:${ref.module}:${ref.processId}:${ref.entity}:${ref.recordId}`;',
    '}',
    '',
    'function pending(ctx: RequestContext, action: string, ref: Omit<OccurrenceRef, \'workflowVersion\'>): void {',
    '  ctx.log.info(\'TASK_ADAPTER_PENDING: the collab-messages Task of a module occurrence does not exist yet; kept in memory.\', { action, ref });',
    '}',
    '',
    'export const taskOccurrence: TaskOccurrencePort = {',
    '  async open(ctx, ref, step, actorNow, key) {',
    '    const opened = key ? byKey.get(key) : undefined;',
    '    if (opened) return byRecord.get(opened)!;',
    '    const id = recordKey(ref);',
    '    const existing = byRecord.get(id);',
    '    if (existing) return existing;',
    '    pending(ctx, \'open\', ref);',
    '    const occurrence: TaskOccurrence = { ref, step, actorNow, history: [{ step, actor: actorNow, at: ctx.clock.nowIso() }], openedBy: key };',
    '    byRecord.set(id, occurrence);',
    '    if (key) byKey.set(key, id);',
    '    return occurrence;',
    '  },',
    '  async find(_ctx, ref) {',
    '    return byRecord.get(recordKey(ref)) ?? null;',
    '  },',
    '  async advance(ctx, ref, step, actorNow) {',
    '    const occurrence = byRecord.get(recordKey(ref));',
    '    if (!occurrence) throw new Error(`OCCURRENCE_NOT_FOUND: ${recordKey(ref)} was never opened.`);',
    '    pending(ctx, \'advance\', ref);',
    '    occurrence.step = step;',
    '    occurrence.actorNow = actorNow;',
    '    occurrence.history.push({ step, actor: actorNow, at: ctx.clock.nowIso() });',
    '    return occurrence;',
    '  },',
    '};',
    '',
  ].join('\n');
}

/**
 * The module tick: the minute the platform lends (`moduleTick.ts` of 102034) runs every scheduled process of the
 * module, each through the `onTick` its workflow file exports. A failing process is logged and the others still run.
 */
export function moduleTickSource(project: number, moduleName: string, processIds: readonly string[]): string {
  const info = moduleTickFile(project, moduleName);
  return [
    `/// <mls fileReference="_${project}_/l1/${info.folder}/${info.shortName}.ts" enhancement="_blank"/>`,
    `import type { RequestContext } from '${PLATFORM_CONTRACTS}';`,
    ...processIds.map(processId => `import { onTick as ${processId}Tick } from '${moduleSpecifier(workflowFile(project, moduleName, processId))}';`),
    '',
    '// Generated by agentMaterializeL1 (materializadorL1.md §11): the scheduled processes of the module.',
    'export async function onTick(ctx: RequestContext, now: Date): Promise<void> {',
    ...processIds.flatMap(processId => [
      '  try {',
      `    await ${processId}Tick(ctx, now);`,
      '  } catch (error) {',
      `    ctx.log.error('TICK_FAILED: ${moduleName}.${processId}', { error: error instanceof Error ? error.message : String(error) });`,
      '  }',
    ]),
    '}',
    '',
  ].join('\n');
}
