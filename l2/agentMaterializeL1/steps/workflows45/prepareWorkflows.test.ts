const PROJECT = 1;
const MODULE = 'mod';

interface FakeFile extends M12FileInfo {
  status: string;
  content: string;
  getContent(): Promise<string>;
  getValueInfo(): Promise<{ content: string }>;
}

function keyOf(info: M12FileInfo): string {
  return `${info.project}_${info.level}_${info.folder}/${info.shortName}${info.extension}`;
}

function install(present: Array<{ info: M12FileInfo; content: string; status?: string }>): Record<string, FakeFile> {
  const files: Record<string, FakeFile> = {};
  const put = (info: M12FileInfo, content: string, status = 'changed'): FakeFile => {
    const stored: FakeFile = {
      ...info, status, content,
      getContent: async () => stored.content,
      getValueInfo: async () => ({ content: stored.content }),
    };
    files[keyOf(info)] = stored;
    return stored;
  };
  for (const item of present) put(item.info, item.content, item.status);
  (globalThis as { mls: unknown }).mls = {
    stor: {
      files,
      getKeyToFile: keyOf,
      addOrUpdateFile: async (info: M12FileInfo) => files[keyOf(info)] ?? put(info, '', 'new'),
      localStor: {
        setContent: async (stored: FakeFile, value: { content?: string | null }) => { stored.content = value.content ?? ''; return true; },
      },
    },
  };
  return files;
}

/** `unavailable`: no compiler here; `clean`: the compiler answers without errors; an array: the compiler answers with those errors. */
type Compiled = 'unavailable' | 'clean' | readonly string[];

function ctx(force: boolean, compiled: Compiled = 'unavailable', moduleName = MODULE): { context: M12Context; reads: () => number; compiles: () => number } {
  let reads = 0;
  let compiles = 0;
  const compiler: M12Compiler = {
    available: () => { compiles += 1; return compiled !== 'unavailable'; },
    enter: () => undefined,
    leave: () => undefined,
    read: async (info: M12FileInfo) => readOptional(info),
    model: async (info: M12FileInfo) => {
      const text = await readOptional(info);
      return { model: { getValue: () => text ?? '' } } as never;
    },
    preload: async () => [],
    compile: async () => ({ errors: compiled === 'unavailable' || compiled === 'clean' ? [] : [...compiled] }),
  };
  return {
    reads: () => reads,
    compiles: () => compiles,
    context: {
      run: { project: PROJECT, module: moduleName, scope: '', target: '', force },
      units: [],
      appEnv: 'presentation',
      read: async () => { reads += 1; return null; },
      compiler,
    },
  };
}

const engine = workflowEngineFile(PROJECT, MODULE);

void test('an existing engine.ts is kept without reading sources, and is compiled again', async () => {
  install([{ info: engine, content: 'export const stale = 1;\n' }]);
  const harness = ctx(false);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: kept: exists; written, not compiled (COMPILE_UNAVAILABLE_L1)']);
  assert.equal(await readOptional(engine), 'export const stale = 1;\n');
  assert.equal(harness.reads(), 0);
  assert.equal(harness.compiles(), 1);
});

void test('a missing engine.ts is written', async () => {
  install([]);
  const harness = ctx(false);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: written, not compiled (COMPILE_UNAVAILABLE_L1)']);
  assert.match(await readOptional(engine) ?? '', /Generated by agentMaterializeL1/u);
  assert.ok(harness.reads() > 0);
  assert.equal(harness.compiles(), 1);
});

void test('a deleted engine.ts is generated again', async () => {
  install([{ info: engine, content: 'old', status: 'deleted' }]);
  const harness = ctx(false);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: written, not compiled (COMPILE_UNAVAILABLE_L1)']);
  assert.match(await readOptional(engine) ?? '', /Generated by agentMaterializeL1/u);
});

void test('engine.defs.ts does not count as engine.ts', async () => {
  install([{ info: { ...engine, extension: '.defs.ts' }, content: 'export const definition = {} as const;\n' }]);
  const harness = ctx(false);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: written, not compiled (COMPILE_UNAVAILABLE_L1)']);
});

void test('force rewrites an existing engine.ts', async () => {
  install([{ info: engine, content: 'export const stale = 1;\n' }]);
  const harness = ctx(true);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: written, not compiled (COMPILE_UNAVAILABLE_L1)']);
  assert.match(await readOptional(engine) ?? '', /Generated by agentMaterializeL1/u);
  assert.equal(harness.compiles(), 1);
});

async function engineStatus(moduleName = MODULE): Promise<M12UnitStatus | null> {
  return readUnitStatus(PROJECT, moduleName, 'workflows', 'engine');
}

void test('the engine compile outcome is recorded as the workflows/engine unit: error, unavailable and clean', async () => {
  install([]);
  const failing = ctx(false, ['engine.ts(1,1): error TS2339: nope']);
  const lines = await prepareWorkflows(failing.context);
  assert.match(lines[0] ?? '', /^workflowEngine: COMPILE_FAILED /u);
  const failed = await engineStatus();
  assert.equal(failed?.status, 'failed');
  assert.equal(failed?.code, 'COMPILE_FAILED');
  assert.match(failed?.diagnostic ?? '', /TS2339/u);

  install([]);
  const unavailable = await prepareWorkflows(ctx(false, ['M12_COMPILE_UNAVAILABLE_L1: no compiler']).context);
  assert.deepEqual(unavailable, ['workflowEngine: written, not compiled (COMPILE_UNAVAILABLE_L1)']);
  const notProved = await engineStatus();
  assert.equal(notProved?.status, 'done');
  assert.equal(notProved?.code, 'COMPILE_UNAVAILABLE_L1');

  install([]);
  assert.deepEqual(await prepareWorkflows(ctx(false, 'clean').context), ['workflowEngine: written']);
  const clean = await engineStatus();
  assert.equal(clean?.status, 'done');
  assert.equal(clean?.code, '');
});

void test('an engine that already exists is compiled again, and its error is recorded', async () => {
  // Another module: readOptional serves the bytes this session wrote first, and the tests above wrote the engine of `mod`.
  const kept = workflowEngineFile(PROJECT, 'keptmod');
  install([{ info: kept, content: 'export const stale: number = "x";\n' }]);
  const harness = ctx(false, ['engine.ts(1,14): error TS2322: bad'], 'keptmod');
  const lines = await prepareWorkflows(harness.context);
  assert.match(lines[0] ?? '', /^workflowEngine: kept: exists; COMPILE_FAILED /u);
  assert.equal(await readOptional(kept), 'export const stale: number = "x";\n');
  assert.equal(harness.reads(), 0, 'the sources are not read again');
  assert.equal(harness.compiles(), 1);
  const status = await engineStatus('keptmod');
  assert.equal(status?.status, 'failed');
  assert.equal(status?.code, 'COMPILE_FAILED');
});

void test('the report is partial with a failed workflows/engine unit and lists a not compiled one in notCompiled', () => {
  const status = (state: M12UnitStatus['status'], code: string): M12UnitStatus => ({ schemaVersion: '2026-10-05-m12-unit-v1', layer: 'workflows', unitId: 'engine', defRef: '', status: state, code, attempt: 0, diagnostic: code, inputHash: '', outputs: {}, updatedAt: '' });
  const failed = buildM12Report(PROJECT, MODULE, [status('failed', 'COMPILE_FAILED')], [], [], null);
  assert.equal(failed.status, 'partial');
  assert.deepEqual(failed.open.map(item => `${item.layer}/${item.unitId}:${item.code}`), ['workflows/engine:COMPILE_FAILED']);
  assert.deepEqual(failed.notCompiled, []);
  const unavailable = buildM12Report(PROJECT, MODULE, [status('done', 'COMPILE_UNAVAILABLE_L1')], [], [], null);
  assert.equal(unavailable.status, 'complete');
  assert.deepEqual(unavailable.notCompiled, ['workflows/engine']);
  assert.deepEqual(unavailable.open, []);
  const clean = buildM12Report(PROJECT, MODULE, [status('done', '')], [], [], null);
  assert.equal(clean.status, 'complete');
  assert.deepEqual(clean.notCompiled, []);
});
