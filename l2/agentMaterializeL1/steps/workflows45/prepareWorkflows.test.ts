async function engineStatus(moduleName = MODULE): Promise<M12UnitStatus | null> {
  return readUnitStatus(PROJECT, moduleName, 'workflows', 'engine');
}

void test('the engine compile outcome is recorded as the workflows/engine unit: error, unavailable and clean', async () => {
  install([]);
  const failing = ctx(false, ['engine.ts(1,1): error TS2339: nope']);
  const lines = await prepareWorkflows(failing.context);
  assert.match(lines[0] ?? '', /^workflowEngine: COMPILE_FAILED /u);
  const failed = await engineStatus();
  assert.equal(failed?.status, 'failed');
  assert.equal(failed?.code, 'COMPILE_FAILED');
  assert.match(failed?.diagnostic ?? '', /TS2339/u);

  install([]);
  const unavailable = await prepareWorkflows(ctx(false, ['M12_COMPILE_UNAVAILABLE_L1: no compiler']).context);
  assert.deepEqual(unavailable, ['workflowEngine: written, not compiled (COMPILE_UNAVAILABLE_L1)']);
  const notProved = await engineStatus();
  assert.equal(notProved?.status, 'done');
  assert.equal(notProved?.code, 'COMPILE_UNAVAILABLE_L1');

  install([]);
  assert.deepEqual(await prepareWorkflows(ctx(false, 'clean').context), ['workflowEngine: written']);
  const clean = await engineStatus();
  assert.equal(clean?.status, 'done');
  assert.equal(clean?.code, '');
});

void test('an engine that already exists is compiled again, and its error is recorded', async () => {
  // Another module: readOptional serves the bytes this session wrote first, and the tests above wrote the engine of `mod`.
  const kept = workflowEngineFile(PROJECT, 'keptmod');
  install([{ info: kept, content: 'export const stale: number = "x";\n' }]);
  const harness = ctx(false, ['engine.ts(1,14): error TS2322: bad'], 'keptmod');
  const lines = await prepareWorkflows(harness.context);
  assert.match(lines[0] ?? '', /^workflowEngine: kept: exists; COMPILE_FAILED /u);
  assert.equal(await readOptional(kept), 'export const stale: number = "x";\n');
  assert.equal(harness.reads(), 0, 'the sources are not read again');
  assert.equal(harness.compiles(), 1);
  const status = await engineStatus('keptmod');
  assert.equal(status?.status, 'failed');
  assert.equal(status?.code, 'COMPILE_FAILED');
});

void test('the report is partial with a failed workflows/engine unit and lists a not compiled one in notCompiled', () => {
  const status = (state: M12UnitStatus['status'], code: string): M12UnitStatus => ({ schemaVersion: '2026-10-05-m12-unit-v1', layer: 'workflows', unitId: 'engine', defRef: '', status: state, code, attempt: 0, diagnostic: code, inputHash: '', outputs: {}, updatedAt: '' });
  const failed = buildM12Report(PROJECT, MODULE, [status('failed', 'COMPILE_FAILED')], [], [], null);
  assert.equal(failed.status, 'partial');
  assert.deepEqual(failed.open.map(item => `${item.layer}/${item.unitId}:${item.code}`), ['workflows/engine:COMPILE_FAILED']);
  assert.deepEqual(failed.notCompiled, []);
  const unavailable = buildM12Report(PROJECT, MODULE, [status('done', 'COMPILE_UNAVAILABLE_L1')], [], [], null);
  assert.equal(unavailable.status, 'complete');
  assert.deepEqual(unavailable.notCompiled, ['workflows/engine']);
  assert.deepEqual(unavailable.open, []);
  const clean = buildM12Report(PROJECT, MODULE, [status('done', '')], [], [], null);
  assert.equal(clean.status, 'complete');
  assert.deepEqual(clean.notCompiled, []);
});

// d1_347 s6: the engine is rewritten, with `force`, only by a run that regenerates every process of the module (stage 2 key on); off, `force` rewrites it as before.
// Each test has a module of its own: the stor of the harness is not reset between them.
const proc = (unitId: string) => ({ layer: 'workflows', unitId, definition: { artifactType: 'workflowProcess', artifactId: unitId, data: {} } }) as never;

function withUnits(force: boolean, moduleName: string, target: string, units: unknown[]): ReturnType<typeof ctx> {
  const harness = ctx(force, 'unavailable', moduleName);
  harness.context.run.target = target;
  (harness.context as { units: unknown[] }).units = units;
  return harness;
}

async function inStage2<T>(on: boolean, run: () => Promise<T>): Promise<T> {
  const before = stage2.on;
  stage2.on = on;
  try { return await run(); } finally { stage2.on = before; }
}

const STALE = 'export const stale = 1;\n';

void test('d1_347 s6: off, force rewrites an existing engine.ts whatever the run selects (the behavior before stage 2)', async () => {
  const eng = workflowEngineFile(PROJECT, 's6off');
  install([{ info: eng, content: STALE }]);
  const lines = await prepareWorkflows(withUnits(true, 's6off', '', [proc('a'), proc('b')]).context, [proc('a')]);
  assert.match(lines[0], /^workflowEngine: written/u);
  assert.match(await readOptional(eng) ?? '', /Generated by agentMaterializeL1/u);
});

void test('d1_347 s6: on, a run that does not select every process (a target of one process, a run of another layer) keeps and proves the engine', async () => {
  await inStage2(true, async () => {
    const eng = workflowEngineFile(PROJECT, 's6keep');
    for (const selected of [[proc('a')], undefined]) {
      install([{ info: eng, content: STALE }]);
      const harness = withUnits(true, 's6keep', `_${PROJECT}_/l1/s6keep/layer_2_application/workflows/a.defs.ts`, [proc('a'), proc('b')]);
      const lines = await prepareWorkflows(harness.context, selected);
      assert.match(lines[0], /^workflowEngine: kept: a run that does not regenerate every process of the module does not rewrite the engine/u);
      assert.equal(await readOptional(eng), STALE, 'the file is the one on disk');
      assert.equal(harness.compiles(), 1, 'and it is proved again');
    }
  });
});

void test('d1_347 s6: on, a target of the engine file alone is a named failure, and the engine stays', async () => {
  await inStage2(true, async () => {
    const eng = workflowEngineFile(PROJECT, 's6engine');
    install([{ info: eng, content: STALE }]);
    const lines = await prepareWorkflows(withUnits(true, 's6engine', fileRef(eng), [proc('a'), proc('b')]).context, []);
    assert.match(lines[0], /ENGINE_NEEDS_PROCESSES: .* alone, and every process of the module uses it/u);
    assert.match(lines[0], /scope "s6engine\/layer_2_application\/workflows" with force/u);
    assert.equal(await readOptional(eng), STALE);
    const status = await readUnitStatus(PROJECT, 's6engine', 'workflows', 'engine');
    assert.equal(status?.status, 'failed');
    assert.equal(status?.code, 'ENGINE_NEEDS_PROCESSES');
  });
});

void test('d1_347 s6: on, a run that selects every process of the module rewrites the engine with them', async () => {
  await inStage2(true, async () => {
    const eng = workflowEngineFile(PROJECT, 's6all');
    install([{ info: eng, content: STALE }]);
    const lines = await prepareWorkflows(withUnits(true, 's6all', '', [proc('a'), proc('b')]).context, [proc('a'), proc('b')]);
    assert.match(lines[0], /^workflowEngine: written/u);
    assert.match(await readOptional(eng) ?? '', /Generated by agentMaterializeL1/u);
  });
});
