import assert from 'node:assert/strict';
import test from 'node:test';

import type { M12Compiler } from '/_102021_/l2/agentMaterializeL1/helpers/m12Compile.js';
import { readOptional } from '/_102021_/l2/agentMaterializeL1/helpers/m12Io.js';
import type { M12Context } from '/_102021_/l2/agentMaterializeL1/helpers/m12Materialize.js';
import type { M12FileInfo } from '/_102021_/l2/agentMaterializeL1/helpers/m12Names.js';
import { workflowEngineFile } from '/_102021_/l2/agentMaterializeL1/emitters/workflowEmit.js';
import { prepareWorkflows } from '/_102021_/l2/agentMaterializeL1/steps/workflows45/context.js';

const PROJECT = 1;
const MODULE = 'mod';

interface FakeFile extends M12FileInfo {
  status: string;
  content: string;
  getContent(): Promise<string>;
  getValueInfo(): Promise<{ content: string }>;
}

function keyOf(info: M12FileInfo): string {
  return `${info.project}_${info.level}_${info.folder}/${info.shortName}${info.extension}`;
}

function install(present: Array<{ info: M12FileInfo; content: string; status?: string }>): Record<string, FakeFile> {
  const files: Record<string, FakeFile> = {};
  const put = (info: M12FileInfo, content: string, status = 'changed'): FakeFile => {
    const stored: FakeFile = {
      ...info, status, content,
      getContent: async () => stored.content,
      getValueInfo: async () => ({ content: stored.content }),
    };
    files[keyOf(info)] = stored;
    return stored;
  };
  for (const item of present) put(item.info, item.content, item.status);
  (globalThis as { mls: unknown }).mls = {
    stor: {
      files,
      getKeyToFile: keyOf,
      addOrUpdateFile: async (info: M12FileInfo) => files[keyOf(info)] ?? put(info, '', 'new'),
      localStor: {
        setContent: async (stored: FakeFile, value: { content?: string | null }) => { stored.content = value.content ?? ''; return true; },
      },
    },
  };
  return files;
}

function ctx(force: boolean): { context: M12Context; reads: () => number; compiles: () => number } {
  let reads = 0;
  let compiles = 0;
  const compiler: M12Compiler = {
    available: () => { compiles += 1; return false; },
    enter: () => undefined,
    leave: () => undefined,
    read: async () => null,
    model: async () => null,
    preload: async () => [],
    compile: async () => ({ errors: [] }),
  };
  return {
    reads: () => reads,
    compiles: () => compiles,
    context: {
      run: { project: PROJECT, module: MODULE, scope: '', target: '', force },
      units: [],
      appEnv: 'presentation',
      read: async () => { reads += 1; return null; },
      compiler,
    },
  };
}

const engine = workflowEngineFile(PROJECT, MODULE);

void test('an existing engine.ts is kept without reading sources or compiling', async () => {
  install([{ info: engine, content: 'export const stale = 1;\n' }]);
  const harness = ctx(false);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: kept: exists']);
  assert.equal(await readOptional(engine), 'export const stale = 1;\n');
  assert.equal(harness.reads(), 0);
  assert.equal(harness.compiles(), 0);
});

void test('a missing engine.ts is written', async () => {
  install([]);
  const harness = ctx(false);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: written']);
  assert.match(await readOptional(engine) ?? '', /Generated by agentMaterializeL1/u);
  assert.ok(harness.reads() > 0);
  assert.equal(harness.compiles(), 1);
});

void test('a deleted engine.ts is generated again', async () => {
  install([{ info: engine, content: 'old', status: 'deleted' }]);
  const harness = ctx(false);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: written']);
  assert.match(await readOptional(engine) ?? '', /Generated by agentMaterializeL1/u);
});

void test('engine.defs.ts does not count as engine.ts', async () => {
  install([{ info: { ...engine, extension: '.defs.ts' }, content: 'export const definition = {} as const;\n' }]);
  const harness = ctx(false);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: written']);
});

void test('force rewrites an existing engine.ts', async () => {
  install([{ info: engine, content: 'export const stale = 1;\n' }]);
  const harness = ctx(true);
  assert.deepEqual(await prepareWorkflows(harness.context), ['workflowEngine: written']);
  assert.match(await readOptional(engine) ?? '', /Generated by agentMaterializeL1/u);
  assert.equal(harness.compiles(), 1);
});
